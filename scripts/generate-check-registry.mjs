#!/usr/bin/env node
// Parses every check file in lib/checks/ and emits a registry of
// { id, title, source, severity } for every check the audit engine can emit.
// Runs at build/dev time. Output: lib/checks/registry.generated.ts

import { readFileSync, writeFileSync, readdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const checksDir = join(__dirname, '..', 'lib', 'checks');
const outFile = join(checksDir, 'registry.generated.ts');

const fileToSource = {
  'gtmChecks.ts': 'gtm',
  'advancedGTMChecks.ts': 'gtm',
  'adsChecks.ts': 'ads',
  'advancedAdsChecks.ts': 'ads',
  'adsReportChecks.ts': 'report',
  'performanceChecks.ts': 'report',
  'crossChecks.ts': 'cross',
  'advancedCrossChecks.ts': 'cross',
  'settingsReportCrossChecks.ts': 'cross',
  'edgeCaseChecks.ts': 'cross',
  'signalQualityChecks.ts': 'report',
  'structureChecks.ts': 'ads',
  'metaChecks.ts': 'meta',
  'tiktokChecks.ts': 'tiktok',
  'linkedinChecks.ts': 'linkedin',
  'pinterestChecks.ts': 'pinterest',
  'twitterChecks.ts': 'twitter',
  'snapchatChecks.ts': 'snapchat',
};

const files = readdirSync(checksDir).filter(
  (f) => f.endsWith('.ts') && fileToSource[f]
);

const seen = new Map();

for (const file of files) {
  const source = fileToSource[file];
  const content = readFileSync(join(checksDir, file), 'utf8');

  // Match return-block style: id followed by severity and title nearby.
  const blockRe = /id:\s*'([^']+)'[\s\S]{0,400}?title:\s*'([^']+)'/g;
  let m;
  while ((m = blockRe.exec(content)) !== null) {
    const [, id, title] = m;
    if (seen.has(id)) continue;

    // Probe nearest severity literal within ±300 chars for a default.
    const slice = content.slice(Math.max(0, m.index - 300), m.index + 400);
    const sevMatch = slice.match(/severity:\s*'(critical|warning|info)'/);
    const severity = sevMatch ? sevMatch[1] : 'info';

    seen.set(id, { id, title, source, severity });
  }
}

const entries = [...seen.values()].sort((a, b) => a.id.localeCompare(b.id));

const banner = `// AUTO-GENERATED by scripts/generate-check-registry.mjs.
// Do not edit by hand. Re-run \`bun run gen:registry\` after adding checks.
// Source of truth for every check ID the audit engine can emit.
`;

const body = `${banner}
import type { ExplainerSource } from './explainers';

export interface CheckRegistryEntry {
  id: string;
  title: string;
  source: ExplainerSource;
  severity: 'critical' | 'warning' | 'info';
}

export const checkRegistry: CheckRegistryEntry[] = ${JSON.stringify(entries, null, 2)};

export const checkRegistryById: Record<string, CheckRegistryEntry> = Object.fromEntries(
  checkRegistry.map((entry) => [entry.id, entry])
);
`;

writeFileSync(outFile, body);
console.log(`Wrote ${entries.length} check entries to ${outFile}`);
